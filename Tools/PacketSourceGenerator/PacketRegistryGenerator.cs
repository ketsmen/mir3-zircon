using System;
using System.Collections.Generic;
using System.Collections.Immutable;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace PacketSourceGenerator
{
    [Generator]
    public sealed class PacketRegistryGenerator : IIncrementalGenerator
    {
        private const string PacketBaseType = "Library.Network.Packet";
        private const string GeneralPacketsNamespace = "Library.Network.GeneralPackets";
        private const string ClientPacketsNamespace = "Library.Network.ClientPackets";
        private const string ServerPacketsNamespace = "Library.Network.ServerPackets";

        public void Initialize(IncrementalGeneratorInitializationContext context)
        {
            IncrementalValuesProvider<INamedTypeSymbol> packetTypes = context.SyntaxProvider
                .CreateSyntaxProvider(
                    static (node, _) => node is ClassDeclarationSyntax { BaseList: not null },
                    static (syntaxContext, _) => GetPacketSymbol(syntaxContext))
                .Where(static symbol => symbol != null)
                .Select(static (symbol, _) => symbol!);

            context.RegisterSourceOutput(packetTypes.Collect(), static (sourceContext, packets) => Execute(sourceContext, packets));
        }

        private static INamedTypeSymbol? GetPacketSymbol(GeneratorSyntaxContext context)
        {
            ClassDeclarationSyntax declaration = (ClassDeclarationSyntax)context.Node;
            if (context.SemanticModel.GetDeclaredSymbol(declaration) is not INamedTypeSymbol symbol)
                return null;

            INamedTypeSymbol? baseType = symbol.BaseType;
            if (baseType == null) return null;

            return string.Equals(baseType.ToDisplayString(), PacketBaseType, StringComparison.Ordinal)
                ? symbol
                : null;
        }

        private static void Execute(SourceProductionContext context, ImmutableArray<INamedTypeSymbol> packetSymbols)
        {
            List<INamedTypeSymbol> packets = new List<INamedTypeSymbol>();

            foreach (INamedTypeSymbol packet in packetSymbols)
            {
                if (packets.Any(existing => SymbolEqualityComparer.Default.Equals(existing, packet))) continue;

                packets.Add(packet);
            }

            packets.Sort(ComparePacketTypes);

            StringBuilder source = new StringBuilder();
            source.AppendLine("// <auto-generated />");
            source.AppendLine("using System;");
            source.AppendLine("using System.Collections.Generic;");
            source.AppendLine();
            source.AppendLine("namespace Library.Network");
            source.AppendLine("{");
            source.AppendLine("    internal static partial class PacketGeneratedRegistry");
            source.AppendLine("    {");
            source.AppendLine("        static partial void AddGeneratedPacketTypes(List<Type> types)");
            source.AppendLine("        {");

            foreach (INamedTypeSymbol packet in packets)
            {
                source.Append("            types.Add(typeof(");
                source.Append(packet.ToDisplayString(SymbolDisplayFormat.FullyQualifiedFormat));
                source.AppendLine("));");
            }

            source.AppendLine("        }");
            source.AppendLine("    }");
            source.AppendLine("}");

            context.AddSource("PacketGeneratedRegistry.g.cs", SourceText.From(source.ToString(), Encoding.UTF8));
        }

        private static int ComparePacketTypes(INamedTypeSymbol x, INamedTypeSymbol y)
        {
            string xNamespace = x.ContainingNamespace.ToDisplayString();
            string yNamespace = y.ContainingNamespace.ToDisplayString();
            bool xGeneral = string.Equals(xNamespace, GeneralPacketsNamespace, StringComparison.Ordinal);
            bool yGeneral = string.Equals(yNamespace, GeneralPacketsNamespace, StringComparison.Ordinal);

            if (xGeneral || yGeneral)
            {
                if (xGeneral && yGeneral)
                    return string.Compare(x.Name, y.Name, StringComparison.Ordinal);

                return xGeneral ? -1 : 1;
            }

            int nameCompare = string.Compare(x.Name, y.Name, StringComparison.Ordinal);
            if (nameCompare != 0) return nameCompare;

            int namespaceCompare = string.Compare(xNamespace, yNamespace, StringComparison.Ordinal);
            if (namespaceCompare == 0) return 0;

            if (string.Equals(x.Name, "ItemSplit", StringComparison.Ordinal))
            {
                if (string.Equals(xNamespace, ClientPacketsNamespace, StringComparison.Ordinal))
                    return -1;

                if (string.Equals(yNamespace, ClientPacketsNamespace, StringComparison.Ordinal))
                    return 1;
            }

            if (string.Equals(xNamespace, ServerPacketsNamespace, StringComparison.Ordinal))
                return -1;

            if (string.Equals(yNamespace, ServerPacketsNamespace, StringComparison.Ordinal))
                return 1;

            return namespaceCompare;
        }
    }
}
